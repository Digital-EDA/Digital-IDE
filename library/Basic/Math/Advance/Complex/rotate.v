                phase_act <= HPI - phase_abs;
            end 
            else if (phase_abs <= TQPI) begin
                quadrant <= {phase_buf[15], 2'b10};
                phase_act <= phase_abs - HPI;
            end 
            else begin
                quadrant <= {phase_buf[15], 2'b11};
                phase_act <= OPI - phase_abs;
            end

            // cycle 3
            // wait for raw_rot_i
            quadrant_buf <= quadrant;

            // cycle 4
            case(quadrant_buf)
                3'b000: begin
                    rot_i <= raw_rot_i;
                    rot_q <= raw_rot_q;
                end
                3'b001: begin
                    rot_i <= raw_rot_q;
                    rot_q <= raw_rot_i;
                end
                3'b010: begin
                    rot_i <= ~raw_rot_q+1;
                    rot_q <= raw_rot_i;
                end
                3'b011: begin
                    rot_i <= ~raw_rot_i+1;
                    rot_q <= raw_rot_q;
                end
                3'b100: begin
                    rot_i <= raw_rot_i;
                    rot_q <= ~raw_rot_q+1;
                end
                3'b101: begin
                    rot_i <= raw_rot_q;
                    rot_q <= ~raw_rot_i+1;
                end
                3'b110: begin
                    rot_i <= ~raw_rot_q+1;
                    rot_q <= ~raw_rot_i+1;
                end
                3'b111: begin
                    rot_i <= ~raw_rot_i+1;
                    rot_q <= ~raw_rot_q+1;
                end
            endcase
        end
